"""Deterministic ESM-to-classic adaptation: no bundler or dynamic app script."""
import hashlib
import json
from pathlib import Path
root=Path(__file__).resolve().parent
source=(root/'static/tracker.mjs').read_bytes()
classic=b'// Generated by build_tracker.py; edit tracker.mjs instead.\n'+source.replace(b'export const ',b'const ').replace(b'export class ',b'class ')
(root/'static/tracker-classic.js').write_bytes(classic)
(root/'static/trackingvendor/tracker-source-manifest.json').write_text(json.dumps({'source':'../tracker.mjs','sourceSha256':hashlib.sha256(source).hexdigest(),'generated':'../tracker-classic.js','generatedSha256':hashlib.sha256(classic).hexdigest(),'adaptation':'Remove only two ESM export declarations; prepend generated header.'},indent=2)+'\n')
